/**
 * Report rendering.
 *
 * SKELETON: this renders a self-contained HTML summary of the compliance result.
 * Real PDF/DOCX generation (e.g. via pdfkit / puppeteer / docx) plugs in here
 * without changing the worker or storage flow — swap `renderReport` to return the
 * rendered bytes and set the appropriate content type/extension.
 */

function esc(v: unknown): string {
  return String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

export interface RenderedReport {
  buffer: Buffer;
  contentType: string;
  extension: string;
}

// `data` is the object returned by reports.service.collectReportData.
export function renderReport(data: Record<string, unknown>, type: 'PDF' | 'DOCX'): RenderedReport {
  const d = data as {
    code: string;
    outcome: string;
    status: string;
    product?: { name?: string };
    declarations: Array<{ type: string; normalizedValue: string | null; confidence: number | null }>;
    violations: Array<{ title: string; severity: string; legalReference: string | null; reason: string | null }>;
    checks: Array<{ status: string; reason: string | null; rule?: { code?: string } }>;
  };

  const html = `<!doctype html>
<html><head><meta charset="utf-8"><title>Compliance Report ${esc(d.code)}</title></head>
<body>
  <h1>Legal Metrology Compliance Report</h1>
  <p><strong>Inspection:</strong> ${esc(d.code)}</p>
  <p><strong>Product:</strong> ${esc(d.product?.name ?? '—')}</p>
  <p><strong>Outcome:</strong> ${esc(d.outcome)} (status: ${esc(d.status)})</p>

  <h2>Declarations (${d.declarations.length})</h2>
  <ul>
    ${d.declarations
      .map((x) => `<li>${esc(x.type)}: ${esc(x.normalizedValue)} (conf: ${esc(x.confidence)})</li>`)
      .join('')}
  </ul>

  <h2>Violations (${d.violations.length})</h2>
  <ul>
    ${d.violations
      .map(
        (v) =>
          `<li>[${esc(v.severity)}] ${esc(v.title)} — ${esc(v.legalReference)} — ${esc(v.reason)}</li>`,
      )
      .join('')}
  </ul>

  <h2>Checks (${d.checks.length})</h2>
  <ul>
    ${d.checks
      .map((c) => `<li>${esc(c.rule?.code)}: ${esc(c.status)} — ${esc(c.reason)}</li>`)
      .join('')}
  </ul>

  <hr>
  <p><em>Generated by the Legal Metrology Compliance Checker. Report format
  placeholder — replace with PDF/DOCX renderer in report.renderer.ts.</em></p>
</body></html>`;

  // NOTE: content is HTML in the skeleton regardless of the requested type.
  return {
    buffer: Buffer.from(html, 'utf-8'),
    contentType: type === 'DOCX' ? 'text/html' : 'text/html',
    extension: 'html',
  };
}
