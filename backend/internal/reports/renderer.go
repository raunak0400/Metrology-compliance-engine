// Report rendering.
//
// SKELETON: this renders a self-contained HTML summary of the compliance
// result, matching the fidelity of the original Node service. Real PDF/DOCX
// generation (e.g. via gofpdf / a headless-Chromium print, or unidoc/unioffice
// for DOCX) plugs in here without changing the worker or storage flow — swap
// Render to return the rendered bytes and set the appropriate content
// type/extension.
package reports

import (
	"fmt"
	"html"
	"strings"
)

type RenderedReport struct {
	Buffer      []byte
	ContentType string
	Extension   string
}

type ReportData struct {
	Code         string
	Outcome      string
	Status       string
	ProductName  string
	Declarations []ReportDeclaration
	Violations   []ReportViolation
	Checks       []ReportCheck
}

type ReportDeclaration struct {
	Type            string
	NormalizedValue string
	Confidence      string
}

type ReportViolation struct {
	Title          string
	Severity       string
	LegalReference string
	Reason         string
}

type ReportCheck struct {
	RuleCode string
	Status   string
	Reason   string
}

// Render produces the report bytes. NOTE: content is HTML in the skeleton
// regardless of the requested type, matching the original placeholder.
func Render(data ReportData, reportType string) RenderedReport {
	var declRows, violRows, checkRows strings.Builder

	for _, d := range data.Declarations {
		fmt.Fprintf(&declRows, "<li>%s: %s (conf: %s)</li>", html.EscapeString(d.Type), html.EscapeString(d.NormalizedValue), html.EscapeString(d.Confidence))
	}
	for _, v := range data.Violations {
		fmt.Fprintf(&violRows, "<li>[%s] %s — %s — %s</li>", html.EscapeString(v.Severity), html.EscapeString(v.Title), html.EscapeString(v.LegalReference), html.EscapeString(v.Reason))
	}
	for _, c := range data.Checks {
		fmt.Fprintf(&checkRows, "<li>%s: %s — %s</li>", html.EscapeString(c.RuleCode), html.EscapeString(c.Status), html.EscapeString(c.Reason))
	}

	page := fmt.Sprintf(`<!doctype html>
<html><head><meta charset="utf-8"><title>Compliance Report %s</title></head>
<body>
  <h1>Legal Metrology Compliance Report</h1>
  <p><strong>Inspection:</strong> %s</p>
  <p><strong>Product:</strong> %s</p>
  <p><strong>Outcome:</strong> %s (status: %s)</p>

  <h2>Declarations (%d)</h2>
  <ul>%s</ul>

  <h2>Violations (%d)</h2>
  <ul>%s</ul>

  <h2>Checks (%d)</h2>
  <ul>%s</ul>

  <hr>
  <p><em>Generated by the Legal Metrology Compliance Checker. Report format
  placeholder — replace with a PDF/DOCX renderer in internal/reports/renderer.go.</em></p>
</body></html>`,
		html.EscapeString(data.Code), html.EscapeString(data.Code),
		orDash(html.EscapeString(data.ProductName)),
		html.EscapeString(data.Outcome), html.EscapeString(data.Status),
		len(data.Declarations), declRows.String(),
		len(data.Violations), violRows.String(),
		len(data.Checks), checkRows.String(),
	)

	return RenderedReport{Buffer: []byte(page), ContentType: "text/html", Extension: "html"}
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}
